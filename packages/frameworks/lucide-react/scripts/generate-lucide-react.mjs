import { promises as fs } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { generateLucideEntries } from '../../../../tools/lucide-generator/index.mjs';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const packageDir = path.resolve(__dirname, '..');
const lucideDir = path.resolve(packageDir, '../../icons/lucide');
const outputDir = path.join(packageDir, 'src/lucide');
const iconsOutputDir = path.join(outputDir, 'icons');

const GENERATED_HEADER = '// This file is auto-generated by scripts/generate-lucide-react.mjs.\n';

async function ensureEmptyDirectory(dirPath) {
  await fs.rm(dirPath, { recursive: true, force: true });
  await fs.mkdir(dirPath, { recursive: true });
}

async function writeFile(filePath, content) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, content, 'utf8');
}

function createTypesFile() {
  return `${GENERATED_HEADER}
import type { SVGProps } from 'react';
import type { IconPixels, IconRects, IconRenderMode, PixelShape } from '@pxicons/lucide-core';

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'color'> {
  name?: string;
  color?: string;
  size?: number | string;
  strokeWidth?: number | string;
  absoluteStrokeWidth?: boolean;
  shape?: PixelShape | string;
  renderMode?: IconRenderMode | string;
  iconPixels?: IconPixels;
  iconRects?: IconRects;
  title?: string;
}
`;
}

function createDefaultAttributesFile() {
  return `${GENERATED_HEADER}
const defaultAttributes = {
  xmlns: 'http://www.w3.org/2000/svg',
  viewBox: '0 0 24 24',
  fill: 'none'
} as const;

export default defaultAttributes;
`;
}

function createIconBaseFile() {
  return `${GENERATED_HEADER}
import { forwardRef, type ReactNode } from 'react';

import { hasA11yProp, resolveIconRenderModel, type PixelShape } from '@pxicons/lucide-core';

import defaultAttributes from './default-attributes.js';
import type { IconProps } from './types.js';

function formatNumber(value: number): string {
  const rounded = Math.round(value * 1000) / 1000;

  if (Number.isInteger(rounded)) {
    return String(rounded);
  }

  return String(rounded)
    .replace(/\\.0+$/, '')
    .replace(/(\\.\\d*?)0+$/, '$1');
}

function joinClasses(...values: Array<string | undefined>): string {
  const classSet = new Set<string>();

  for (const value of values) {
    if (!value) {
      continue;
    }

    for (const token of value.split(/\\s+/)) {
      const trimmed = token.trim();

      if (trimmed.length > 0) {
        classSet.add(trimmed);
      }
    }
  }

  return [...classSet].join(' ');
}

function buildRawPrimitiveNodes(
  shape: PixelShape,
  iconPixels: readonly (readonly [number, number])[],
  pixelSize: number,
  pixelInset: number,
  roundedCornerRadius: number
): ReactNode[] {
  if (shape === 'circle') {
    return iconPixels.map(([x, y], index) => {
      const cx = x + pixelInset + pixelSize / 2;
      const cy = y + pixelInset + pixelSize / 2;

      return (
        <circle
          key={index}
          cx={formatNumber(cx)}
          cy={formatNumber(cy)}
          r={formatNumber(pixelSize / 2)}
        />
      );
    });
  }

  if (shape === 'rounded') {
    return iconPixels.map(([x, y], index) => {
      const px = x + pixelInset;
      const py = y + pixelInset;

      return (
        <rect
          key={index}
          x={formatNumber(px)}
          y={formatNumber(py)}
          width={formatNumber(pixelSize)}
          height={formatNumber(pixelSize)}
          rx={formatNumber(roundedCornerRadius)}
          ry={formatNumber(roundedCornerRadius)}
        />
      );
    });
  }

  return iconPixels.map(([x, y], index) => {
    const px = x + pixelInset;
    const py = y + pixelInset;

    return (
      <rect
        key={index}
        x={formatNumber(px)}
        y={formatNumber(py)}
        width={formatNumber(pixelSize)}
        height={formatNumber(pixelSize)}
      />
    );
  });
}

const Icon = forwardRef<SVGSVGElement, IconProps>((props, ref) => {
  const {
    name,
    color = 'currentColor',
    size = 24,
    strokeWidth = 2,
    absoluteStrokeWidth = false,
    shape = 'square',
    renderMode = 'auto',
    iconPixels = [],
    iconRects = [],
    className,
    children,
    title,
    ...rest
  } = props;

  const renderModel = resolveIconRenderModel({
    iconPixels,
    iconRects,
    size,
    strokeWidth,
    absoluteStrokeWidth,
    shape,
    renderMode
  });

  const combinedClassName = joinClasses(
    'pxicons-icon lucide-icon lucide',
    name ? 'lucide-' + name : undefined,
    name ? 'pxicons-' + name : undefined,
    className
  );

  const svgProps: IconProps = {
    ...defaultAttributes,
    ...rest,
    width: size,
    height: size,
    className: combinedClassName,
    shapeRendering: 'crispEdges'
  };

  if (!title && !children && !hasA11yProp(rest as Record<string, unknown>)) {
    svgProps['aria-hidden'] = 'true';
  }

  return (
    <svg ref={ref} {...svgProps}>
      {title ? <title>{title}</title> : null}
      <g fill={color}>
        {renderModel.shouldRenderOptimized ? (
          <path d={renderModel.optimizedPathData ?? ''} />
        ) : (
          buildRawPrimitiveNodes(
            renderModel.normalizedShape,
            iconPixels,
            renderModel.pixelSize,
            renderModel.pixelInset,
            renderModel.roundedCornerRadius
          )
        )}
      </g>
      {children}
    </svg>
  );
});

Icon.displayName = 'Icon';

export default Icon;
`;
}

function createIconComponentFile(entry) {
  const pixelsLiteral = JSON.stringify(entry.iconPixels);
  const rectsLiteral = JSON.stringify(entry.iconRects);

  return `${GENERATED_HEADER}
import { forwardRef } from 'react';

import Icon from '../Icon.js';
import type { IconProps } from '../types.js';

const iconPixels = ${pixelsLiteral} as const;
const iconRects = ${rectsLiteral} as const;

const ${entry.componentName} = forwardRef<SVGSVGElement, IconProps>((props, ref) => (
  <Icon
    ref={ref}
    name="${entry.iconId}"
    iconPixels={iconPixels}
    iconRects={iconRects}
    {...props}
  />
));

${entry.componentName}.displayName = '${entry.componentName}';

export default ${entry.componentName};
`;
}

function createIconsIndexFile(entries) {
  const exportLines = entries
    .map(({ componentName, iconId }) => `export { default as ${componentName} } from './${iconId}.js';`)
    .join('\n');

  return `${GENERATED_HEADER}
${exportLines}
`;
}

function createRootIndexFile() {
  return `${GENERATED_HEADER}
export * from './icons/index.js';
export * as icons from './icons/index.js';
export { default as Icon } from './Icon.js';
export type { IconProps } from './types.js';
export type { IconRenderMode, PixelShape } from '@pxicons/lucide-core';
`;
}

async function main() {
  const entries = await generateLucideEntries(lucideDir);

  await ensureEmptyDirectory(iconsOutputDir);

  for (const entry of entries) {
    await writeFile(
      path.join(iconsOutputDir, `${entry.iconId}.tsx`),
      createIconComponentFile(entry)
    );
  }

  await writeFile(path.join(outputDir, 'types.ts'), createTypesFile());
  await writeFile(path.join(outputDir, 'default-attributes.ts'), createDefaultAttributesFile());
  await writeFile(path.join(outputDir, 'Icon.tsx'), createIconBaseFile());
  await writeFile(path.join(outputDir, 'index.ts'), createRootIndexFile());
  await writeFile(path.join(iconsOutputDir, 'index.ts'), createIconsIndexFile(entries));

  console.log(`Generated ${entries.length} Lucide React icon components.`);
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
